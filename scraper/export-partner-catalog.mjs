// 찜한 상품만 협력사 정적 사이트용 catalog.js 로 내보낸다.
// detailHtml 과 로컬 이미지 경로는 넣지 않는다.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { FAV_JSON, ITEMS_JSON } from './lib/paths.mjs';
import { buildPartnerWorkbook, rowsFromCatalog } from './lib/partner-sheet.mjs';

const outDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'partner-site', 'data');
const outFile = path.join(outDir, 'catalog.js');
const outXlsx = path.join(outDir, 'catalog.xlsx');

function readJson(file) {
	return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function num(v) {
	if (v === null || v === undefined || v === '') return null;
	const n = Number(v);
	return Number.isFinite(n) ? n : null;
}

function uniqueFavs(raw) {
	const out = [];
	for (const id of Array.isArray(raw) ? raw : []) {
		const goodsNo = String(id || '').trim();
		if (goodsNo && !out.includes(goodsNo)) out.push(goodsNo);
	}
	return out;
}

function addRank(ranks, next) {
	const i = ranks.findIndex((r) => r.categoryName === next.categoryName);
	if (i === -1) ranks.push(next);
	else if (next.rank !== null && (ranks[i].rank === null || next.rank < ranks[i].rank)) ranks[i] = next;
}

function toProduct(group) {
	const it = group.best;
	const seen = new Set();
	const gallery = [];
	for (const img of it.detailImages || []) {
		const url = img && typeof img.url === 'string' ? img.url : '';
		if (!url.startsWith('https://') || seen.has(url)) continue;
		seen.add(url);
		gallery.push(url);
	}
	return {
		goodsNo: it.goodsNo,
		name: it.name || '',
		brand: it.brand || '',
		categoryPath: it.categoryPath || '',
		normalPrice: num(it.normalPrice),
		salePrice: num(it.salePrice),
		effectivePrice: num(it.effectivePrice),
		discountRate: num(it.discountRate),
		flags: Array.isArray(it.flags) ? it.flags : [],
		imageUrl: typeof it.imageUrl === 'string' ? it.imageUrl : '',
		detailUrl: typeof it.detailUrl === 'string' ? it.detailUrl : '',
		gallery,
		article: it.article && typeof it.article === 'object' ? it.article : null,
		ranks: group.ranks
	};
}

function buildCatalog() {
	if (!fs.existsSync(ITEMS_JSON)) {
		throw new Error('수집 결과가 없습니다: ' + ITEMS_JSON);
	}
	const payload = readJson(ITEMS_JSON);
	const favs = uniqueFavs(fs.existsSync(FAV_JSON) ? readJson(FAV_JSON) : []);
	const groups = new Map(favs.map((goodsNo) => [goodsNo, { best: null, bestScore: -1, ranks: [] }]));

	for (const category of payload.categories || []) {
		for (const it of category.items || []) {
			const group = groups.get(it.goodsNo);
			if (!group) continue;
			const score = (it.detailHtml ? 2 : 0) + (it.article ? 1 : 0);
			if (score > group.bestScore) {
				group.best = it;
				group.bestScore = score;
			}
			addRank(group.ranks, {
				categoryName: category.name,
				rank: num(it.rank),
				rankingType: it.rankingType || null
			});
		}
	}

	const products = [];
	const missing = [];
	for (const goodsNo of favs) {
		const group = groups.get(goodsNo);
		if (!group || !group.best) missing.push(goodsNo);
		else products.push(toProduct(group));
	}

	return {
		exportedAt: new Date().toISOString(),
		sourceGeneratedAt: payload.generatedAt || null,
		products,
		missing
	};
}

const catalog = buildCatalog();
fs.mkdirSync(outDir, { recursive: true });
const js = '/* Generated by scraper/export-partner-catalog.mjs. Do not edit. */\nwindow.PARTNER_CATALOG = ' + JSON.stringify(catalog, null, 2) + ';\n';
fs.writeFileSync(outFile, js);
fs.writeFileSync(outXlsx, buildPartnerWorkbook(rowsFromCatalog(catalog.products)));
console.log(`협력사 카탈로그 ${catalog.products.length}건 → ${outFile}`);
console.log(`협력사 엑셀 ${catalog.products.length}건 → ${outXlsx}`);
if (catalog.missing.length) console.log('수집 JSON에 없는 찜:', catalog.missing.join(', '));
